#!/usr/bin/env python3
"""Check or refresh source snapshots from an explicit native protocol generator."""

import argparse
from pathlib import Path
import subprocess
import tempfile


MARKER = b"GENERATED by tidepool-protocol, DO NOT EDIT."


def declared_paths(root):
    declared = (root / "build/protocol/outputs.txt").read_text().splitlines()
    paths = [Path(name) for name in declared]
    if not paths or len(set(paths)) != len(paths):
        raise ValueError("protocol output roster must be nonempty and unique")
    if any(path.is_absolute() or ".." in path.parts for path in paths):
        raise ValueError("protocol outputs must be relative paths within the source root")
    return paths


def compare(root, output, paths, refresh=False):
    wanted = set(paths)
    stale = []
    for directory in sorted({(root / path).parent for path in paths}):
        if not directory.exists():
            continue
        for source in directory.iterdir():
            if source.is_file() and source.relative_to(root) not in wanted:
                with source.open("rb") as stream:
                    if MARKER in stream.readline():
                        stale.append(source)
    changed = []
    for path in paths:
        source, generated = root / path, output / path
        contents = generated.read_bytes()
        if not source.is_file() or source.read_bytes() != contents:
            changed.append(path)
    # Materialize and validate all producer outputs before modifying source.
    if refresh:
        for path in changed:
            source = root / path
            source.parent.mkdir(parents=True, exist_ok=True)
            source.write_bytes((output / path).read_bytes())
        for source in stale:
            source.unlink()
    return changed, sorted(source.relative_to(root) for source in stale)


def reconcile(root, generator, refresh=False):
    paths = declared_paths(root)
    roster = subprocess.check_output([str(generator), "--list"], text=True).splitlines()
    if roster != [path.as_posix() for path in paths]:
        raise ValueError("protocol output roster differs from build/protocol/outputs.txt")
    with tempfile.TemporaryDirectory(prefix="tidepool-protocol-snapshots-") as temporary:
        output = Path(temporary)
        command = [str(generator), "--output-root", str(output)]
        for path in paths:
            command.extend(["--expect-output", path.as_posix()])
        subprocess.run(command, check=True)
        return compare(root, output, paths, refresh)


def main(arguments=None):
    parser = argparse.ArgumentParser(description=__doc__)
    producer = parser.add_mutually_exclusive_group(required=True)
    producer.add_argument("--generator", type=Path,
                        help="exact compiled tidepool-protocol-gen executable")
    producer.add_argument("--generated-root", type=Path,
                         help="declared //bridge/protocol:generated output")
    parser.add_argument("--source-root", type=Path,
                        default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--stamp", type=Path,
                        help="write the declared check output only after successful comparison")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--refresh", action="store_true")
    options = parser.parse_args(arguments)
    root = options.source_root.resolve()
    if options.generated_root:
        if options.refresh:
            parser.error("--refresh requires --generator")
        paths = declared_paths(root)
        generated = options.generated_root.resolve()
        actual = {path.relative_to(generated) for path in generated.rglob("*") if path.is_file()}
        if actual != set(paths):
            raise ValueError("generated tree differs from declared protocol output roster")
        changed, stale = compare(root, generated, paths)
    else:
        changed, stale = reconcile(root, options.generator.resolve(), options.refresh)
    for path in changed:
        print(f"{'refreshed' if options.refresh else 'different'}: {path}")
    for path in stale:
        print(f"{'removed' if options.refresh else 'obsolete'}: {path}")
    status = int(not options.refresh and bool(changed or stale))
    if options.stamp and not status:
        options.stamp.write_text("protocol snapshots match declared generator outputs\n")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
