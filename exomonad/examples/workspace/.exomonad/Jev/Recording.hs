{-# LANGUAGE OverloadedStrings #-}

-- | Versioned observations for durable storage through ordinary filesystem
-- effects. An archive contains no executable payloads or prepared decoders.
-- Reconstruct a query or program and pass 'archiveRecords' to the existing
-- exact-request replay operations in "Jev.Operators".
-- Structural decoding establishes the archive format, not compatibility with
-- a new program or authority to execute it. Occurrence metadata is descriptive.
--
-- Recordings are not complete evaluations: preparation can fail before any
-- request is recorded, and a failed call can leave only a history prefix.
module Jev.Recording
  ( RecordingArchive, recordingArchive, archiveRecords
  , archiveValue, archiveFromValue, encodeArchive, decodeArchive
  , ArchiveDecodeError (..)
  ) where

import Data.Bifunctor (first)
import qualified Data.Map.Strict as Map
import Data.Text (Text)
import Jev.Core.Query (Occurrence (..), Recording (..))
import Tidepool.Aeson (FromJSON, Value (..), object, (.=), fromJSON, resultToEither)
import Tidepool.Aeson.Value (encodeValue, eitherDecodeValue)
import Tidepool.Effects.Core (JevCallError)

newtype RecordingArchive = RecordingArchive [Recording Value JevCallError]
  deriving (Eq, Show)

data ArchiveDecodeError
  = InvalidJSON Text
  | InvalidArchive Text
  | UnsupportedVersion Integer
  | MalformedRecord Int Text
  deriving (Eq, Show)

recordingArchive :: [Recording Value JevCallError] -> RecordingArchive
recordingArchive = RecordingArchive

archiveRecords :: RecordingArchive -> [Recording Value JevCallError]
archiveRecords (RecordingArchive records) = records

-- | Preserve request and raw response Values directly, including exact
-- Scientific numbers. The host error codec is generated by the effect owner.
archiveValue :: RecordingArchive -> Value
archiveValue (RecordingArchive records) = object
  ["version" .= (1 :: Integer), "records" .= map recordValue records]
  where
    recordValue (Recording request occurrences outcome) = object
      [ "request" .= request
      , "occurrences" .= map occurrenceValue occurrences
      , "outcome" .= outcome
      ]
    occurrenceValue (Occurrence index scopes questions) = object
      ["index" .= index, "scopes" .= scopes, "questions" .= questions]

-- | Refuse an unknown version or any malformed record as one typed failure;
-- no decoded prefix is returned. Occurrences are observations, not replay
-- authority: the existing replay owner checks the request itself.
archiveFromValue :: Value -> Either ArchiveDecodeError RecordingArchive
archiveFromValue value = do
  envelope <- first InvalidArchive (fields ["version", "records"] value)
  version <- first InvalidArchive (required "version" envelope >>= structural)
  if version /= (1 :: Integer) then Left (UnsupportedVersion version) else do
    records <- first InvalidArchive (required "records" envelope >>= array)
    RecordingArchive <$> traverse decodeRecord (zip [0..] records)
  where
    decodeRecord (index, record) = first (MalformedRecord index) $ do
      row <- fields ["request", "occurrences", "outcome"] record
      request <- required "request" row
      occurrences <- required "occurrences" row >>= array >>= traverse decodeOccurrence
      outcome <- required "outcome" row >>= structural
      pure (Recording request occurrences outcome)
    decodeOccurrence value' = do
      row <- fields ["index", "scopes", "questions"] value'
      index <- required "index" row >>= structural
      scopes <- required "scopes" row >>= structural
      questions <- required "questions" row >>= structural
      pure (Occurrence index scopes questions)

encodeArchive :: RecordingArchive -> Text
encodeArchive = encodeValue . archiveValue

-- | JSON text parsing uses Tidepool's native intrinsic. Under ordinary GHC
-- the intrinsic is a typechecking stub; use 'archiveFromValue' for pure host
-- structural checks.
decodeArchive :: Text -> Either ArchiveDecodeError RecordingArchive
decodeArchive text = first InvalidJSON (eitherDecodeValue text) >>= archiveFromValue

fields :: [Text] -> Value -> Either Text (Map.Map Text Value)
fields names (Object row)
  | Map.keys row == Map.keys (Map.fromList [(name, ()) | name <- names]) = Right row
  | otherwise = Left "expected exactly the declared fields"
fields _ _ = Left "expected object"

required :: Text -> Map.Map Text Value -> Either Text Value
required name row = maybe (Left ("missing field: " <> name)) Right (Map.lookup name row)

array :: Value -> Either Text [Value]
array (Array values) = Right values
array _ = Left "expected array"

structural :: FromJSON a => Value -> Either Text a
structural = resultToEither . fromJSON
