//! Emission, materialization and validation of embedded Haskell source trees.

use std::path::{Path, PathBuf};

pub fn content_hash(entries: &[(&str, &str)]) -> String {
    crate::digest::of_parts(
        entries
            .iter()
            .flat_map(|(relative, content)| [relative.as_bytes(), content.as_bytes()]),
    )
}

/// Repair a partial or changed tree before publishing its completion marker.
pub fn materialize(entries: &[(&str, &str)], destination: PathBuf) -> std::io::Result<PathBuf> {
    let hash = content_hash(entries);
    let sentinel = destination.join(".complete");
    let complete = std::fs::read_to_string(&sentinel).is_ok_and(|recorded| recorded == hash)
        && entries.iter().all(|(relative, content)| {
            std::fs::read(destination.join(relative)).is_ok_and(|bytes| bytes == content.as_bytes())
        });
    if !complete {
        std::fs::create_dir_all(&destination)?;
        for (relative, content) in entries {
            let path = destination.join(relative);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)?;
            }
            tidepool_atomic_write::write_best_effort(&path, content.as_bytes())?;
        }
        tidepool_atomic_write::write_best_effort(&sentinel, hash.as_bytes())?;
    }
    Ok(destination)
}

/// Compare a selected or captured tree with the complete build-owned bundle.
pub fn verify_embedded(
    root: &Path,
    entries: &[(&str, &str)],
) -> Result<(), Box<dyn std::error::Error>> {
    let actual = crate::cache::source_root_manifest(root)?;
    let mut expected = entries
        .iter()
        .map(|(relative, content)| {
            (
                PathBuf::from(relative),
                blake3::hash(content.as_bytes()).to_hex().to_string(),
            )
        })
        .collect::<Vec<_>>();
    expected.sort_by(|a, b| a.0.cmp(&b.0));
    if actual != expected {
        let differing = actual
            .iter()
            .zip(&expected)
            .position(|(found, embedded)| found != embedded)
            .unwrap_or(actual.len().min(expected.len()));
        return Err(format!(
            "captured embedded Haskell library differs from this build at entry {differing}: found {:?}, embedded {:?}",
            actual.get(differing), expected.get(differing)
        ).into());
    }
    Ok(())
}

/// Emit one source table using the same shipped-source selection as runtime validation.
pub fn emit_bundle(
    root: &Path,
    symbol: &str,
    output: &Path,
) -> Result<(), Box<dyn std::error::Error>> {
    let manifest = crate::cache::shipped_haskell_source_manifest(root)?;
    let mut generated = format!(
        "// @generated by build.rs — embedded Haskell sources.\n\
         pub static {symbol}: &[(&str, &str)] = &[\n"
    );
    for (relative, _) in manifest.files() {
        let path = root.join(relative);
        println!("cargo:rerun-if-changed={}", path.display());
        let relative = relative.to_string_lossy().replace('\\', "/");
        let source = std::fs::read_to_string(path)?;
        generated.push_str(&format!("    ({relative:?}, {source:?}),\n"));
    }
    generated.push_str("];\n");
    println!("cargo:rerun-if-changed={}", root.display());
    write_if_changed(output, &generated)?;
    Ok(())
}

pub fn write_if_changed(path: &Path, contents: &str) -> std::io::Result<()> {
    if std::fs::read(path).is_ok_and(|existing| existing == contents.as_bytes()) {
        return Ok(());
    }
    std::fs::write(path, contents)
}

#[cfg(test)]
mod tests {
    use super::*;

    const SOURCES: &[(&str, &str)] = &[("Tidepool/One.hs", "module Tidepool.One where\n")];

    #[test]
    fn materialization_repairs_a_stale_or_partial_completion_marker() {
        let root = tempfile::tempdir().unwrap();
        let destination = root.path().join("bundle");
        std::fs::create_dir_all(&destination).unwrap();
        std::fs::write(destination.join(".complete"), "not-the-content-digest").unwrap();
        materialize(SOURCES, destination.clone()).unwrap();
        assert_eq!(
            std::fs::read_to_string(destination.join("Tidepool/One.hs")).unwrap(),
            SOURCES[0].1
        );
        assert_eq!(
            std::fs::read_to_string(destination.join(".complete")).unwrap(),
            content_hash(SOURCES)
        );
    }

    #[test]
    fn completion_marker_does_not_hide_changed_or_missing_library_sources() {
        let root = tempfile::tempdir().unwrap();
        let destination = root.path().join("bundle");
        materialize(SOURCES, destination.clone()).unwrap();
        let module = destination.join("Tidepool/One.hs");
        std::fs::write(&module, "changed despite valid marker").unwrap();
        materialize(SOURCES, destination.clone()).unwrap();
        assert_eq!(std::fs::read_to_string(&module).unwrap(), SOURCES[0].1);
        std::fs::remove_file(&module).unwrap();
        materialize(SOURCES, destination).unwrap();
        assert_eq!(std::fs::read_to_string(module).unwrap(), SOURCES[0].1);
    }

    #[test]
    fn selected_source_verification_rejects_changed_missing_and_extra_modules() {
        let root = tempfile::tempdir().unwrap();
        let destination = materialize(SOURCES, root.path().join("bundle")).unwrap();
        verify_embedded(&destination, SOURCES).unwrap();
        let module = destination.join("Tidepool/One.hs");
        std::fs::write(&module, "module Tidepool.One where\nchanged = True\n").unwrap();
        assert!(verify_embedded(&destination, SOURCES).is_err());
        std::fs::remove_file(&module).unwrap();
        assert!(verify_embedded(&destination, SOURCES).is_err());
        materialize(SOURCES, destination.clone()).unwrap();
        std::fs::write(destination.join("Extra.hs"), "module Extra where\n").unwrap();
        assert!(verify_embedded(&destination, SOURCES).is_err());
    }
}
